// Generates sample Word and PDF documents from demonstration data so they can
// be opened, rendered to images and checked visually (scripts/check-reports.sh).
import fs from 'node:fs';
import path from 'node:path';
import { Packer } from 'docx';
import { describe, expect, it } from 'vitest';
import { buildCertificate, buildDpr, buildInspectionReport, buildRegisterReport, type Common, type Library } from '../../src/reports/build';
import { renderDocx } from '../../src/reports/docx';
import type { ImageData, RenderContext } from '../../src/reports/model';
import { pdfDefinition, PDF_FONT_FILES } from '../../src/reports/pdf';
import { fixture } from './report-fixture';

const root = path.resolve(__dirname, '../..');
const out = path.join(root, 'test-results/reports');
fs.mkdirSync(out, { recursive: true });

function jpeg(file: string): ImageData {
  const data = new Uint8Array(fs.readFileSync(file));
  // Read JPEG size from the SOF marker.
  let i = 2;
  while (i < data.length) {
    if (data[i] !== 0xff) break;
    const marker = data[i + 1];
    const len = (data[i + 2] << 8) | data[i + 3];
    if (marker >= 0xc0 && marker <= 0xc3) {
      return { data, height: (data[i + 5] << 8) | data[i + 6], width: (data[i + 7] << 8) | data[i + 8], type: 'jpg' };
    }
    i += 2 + len;
  }
  throw new Error('not a jpeg');
}

const logo = jpeg(path.join(root, 'src/assets/report-logo.jpg'));
const ctx: RenderContext = {
  company: {
    legal_name: 'EnvironmSafe for Engineering, Trading & Services Ltd.', tagline: 'Inspection & Testing Services', website: 'www.environmsafe.com',
    email: 'support@environmsafe.com', phone: '+967 78 340 2932', address: 'Al Buraiqah, Aden, Yemen',
  },
  branding: { navy: '#1B1B3A', accent: '#E39B22', text: '#333333' },
  logo,
};

async function pdfBuffer(def: unknown): Promise<Buffer> {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const pdfMake: any = (await import('pdfmake/build/pdfmake')).default;
  const vfs: Record<string, string> = {};
  for (const f of Object.values(PDF_FONT_FILES)) vfs[f] = fs.readFileSync(path.join(root, 'src/assets/fonts', f)).toString('base64');
  return new Promise((res) => pdfMake.createPdf(def, undefined, { Arial: PDF_FONT_FILES }, vfs).getBuffer((b: Uint8Array) => res(Buffer.from(b))));
}

async function write(name: string, model: Parameters<typeof renderDocx>[0]) {
  const docx = await Packer.toBuffer(renderDocx(model, ctx));
  fs.writeFileSync(path.join(out, `${name}.docx`), docx);
  const pdf = await pdfBuffer(pdfDefinition(model, ctx));
  fs.writeFileSync(path.join(out, `${name}.pdf`), pdf);
  return { docx, pdf };
}

describe('generated documents', () => {
  const f = fixture(jpeg);
  const lib: Library = f.lib;
  const common = (code: string, docNumber: string): Common => ({
    unit: 'bar', lib, sections: f.templates[code].sections, texts: {}, docNumber, revision: 0, date: '2026-10-10',
    preparedBy: 'Demo Inspector', reviewedBy: 'Demo Office Lead', approvedBy: 'General Manager', status: 'Issued',
  });

  it('inspection report (second inspection with carried-over findings, UT trend and photos)', async () => {
    const m = buildInspectionReport(f.inspectionBundle, common('inspection', 'ES/DEMO-EXT-2026-001'));
    const { docx, pdf } = await write('inspection-report', m);
    expect(docx.length).toBeGreaterThan(20_000);
    expect(pdf.subarray(0, 4).toString()).toBe('%PDF');
    const text = JSON.stringify(m);
    expect(text).toContain('Status of previous findings');
    expect(text).not.toMatch(/\b(AI|automat|draft|generated by)\b/i);
  });

  it('daily progress report', async () => {
    const m = buildDpr(f.dprBundle, common('dpr', 'ES/DEMO-PC0001-DPR-003'));
    await write('daily-progress-report', m);
    expect(JSON.stringify(m)).not.toMatch(/\b(AI|automat|draft)\b/i);
  });

  it('PSV certificate', async () => {
    const m = buildCertificate(f.psvCertBundle, { ...common('inspection', 'ES-R-12-001'), sections: [] });
    await write('psv-certificate', m);
    expect(JSON.stringify(m)).toContain('ACCEPTED');
  });

  it('hydrostatic test certificate', async () => {
    await write('hydro-certificate', buildCertificate(f.hydroCertBundle, { ...common('inspection', 'ES-H-2026-001'), sections: [] }));
  });

  it('final report for a job', async () => {
    await write('final-report', buildRegisterReport('final', f.registerBundle, common('final', 'ES/DEMO-FR-2026-01')));
  });

  it('findings follow-up and due register', async () => {
    await write('findings-followup', buildRegisterReport('followup', f.registerBundle, common('followup', 'ES/DEMO-RPT-2026-001')));
    await write('due-register', buildRegisterReport('due_register', f.registerBundle, common('due_register', 'ES/DEMO-RPT-2026-002')));
  });
});
