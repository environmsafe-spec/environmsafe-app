-- Gapless numbering: formats per document type, per company, rollback does not burn numbers.
begin;
select plan(11);

select is(app.next_document_number(tests.es(), 'purchase_order', '2026-11-07'), '2026110701', 'PO format YYYYMMDDNN');
select is(app.next_document_number(tests.es(), 'purchase_order', '2026-11-07'), '2026110702', 'PO second number the same day');
select is(app.next_document_number(tests.es(), 'purchase_order', '2026-11-08'), '2026110801', 'PO counter restarts each day');
select is(app.next_document_number(tests.es(), 'sales_invoice',  '2026-11-07'), 'INV-2026110701', 'Invoice format INV-YYYYMMDDNN');
select is(app.next_document_number(tests.es(), 'payment',        '2026-03-01'), 'PV-2026-0001', 'Payment voucher PV-YYYY-NNNN');
select is(app.next_document_number(tests.es(), 'payment',        '2027-01-01'), 'PV-2027-0001', 'Yearly counter restarts in a new year');
select is(app.next_document_number(tests.other(), 'payment',     '2026-03-01'), 'PV-2026-0001', 'Each company has its own series');

-- A rolled-back transaction gives its number back (no gap)
savepoint s1;
select app.next_document_number(tests.es(), 'receipt', '2026-05-05');
rollback to savepoint s1;
select is(app.next_document_number(tests.es(), 'receipt', '2026-05-05'), 'RV-2026-0001', 'Rolled-back number is reused: no gap');

select alike(app.next_draft_number(), 'DRAFT-%', 'Drafts get a temporary number outside the official series');

-- Master data codes
insert into public.items (company_id, code, name_en, kind) values (tests.es(), 'IGNORED', 'Item A', 'goods'), (tests.es(), '', 'Item B', 'service');
select is((select string_agg(code, ',' order by code) from public.items where company_id = tests.es()), 'IT-0001,IT-0002',
  'Item codes are generated by the database (client value ignored)');
select throws_ok($$update public.items set code = 'IT-9999' where name_en = 'Item A'$$, null, 'code cannot change', 'Codes are immutable');

select * from finish();
rollback;
